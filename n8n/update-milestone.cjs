const fs = require('fs');
const path = require('path');
const file = '/site/public/data/milestones.json';
const encoded = process.argv[2];
if (!encoded) throw new Error('Missing encoded milestone payload');
const input = JSON.parse(Buffer.from(encoded, 'base64url').toString('utf8'));
const allowed = new Set(['idea', 'active', 'paused', 'shipped']);
if (!/^[a-z0-9-]{2,80}$/.test(input.projectId || '')) throw new Error('Invalid projectId');
if (!Number.isInteger(input.progress) || input.progress < 0 || input.progress > 100) throw new Error('progress must be an integer 0..100');
if (!allowed.has(input.status)) throw new Error('Invalid status');
for (const key of ['next', 'note']) if (typeof input[key] !== 'string' || input[key].length > 500) throw new Error(`Invalid ${key}`);
if (!Array.isArray(input.tags) || input.tags.length > 8 || input.tags.some(x => typeof x !== 'string' || x.length > 40)) throw new Error('Invalid tags');
const milestones = JSON.parse(fs.readFileSync(file, 'utf8'));
const now = new Date().toISOString().slice(0, 10);
const index = milestones.findIndex(m => m.id === input.projectId);
const updated = { id: input.projectId, title: input.title || input.projectId, status: input.status, progress: input.progress, next: input.next, note: input.note, tags: input.tags, visibility: 'private', updatedAt: now };
if (index >= 0) updated.title = milestones[index].title;
if (index >= 0) milestones[index] = updated; else milestones.push(updated);
const temporary = file + '.tmp';
fs.writeFileSync(temporary, JSON.stringify(milestones, null, 2) + '\n', 'utf8');
fs.renameSync(temporary, file);
console.log(JSON.stringify({ ok: true, id: updated.id, progress: updated.progress }));